// Every source, in one place, with everything needed to decide about it.
//
// The programme has twenty six blocked sources and the decisions about them
// were living in a markdown report, which is the wrong place: a report goes
// stale and nothing checks it. This is the machine readable version, and the
// family gate, the tools queue and the ingest scripts all read it.
//
// A source declares what it costs, what it is allowed to do, how fast it goes
// wrong, and exactly which families it unblocks. A source with no `unlocks`
// is a source nobody needs.

