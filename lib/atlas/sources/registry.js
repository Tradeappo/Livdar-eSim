export const SOURCE_IDS = Object.keys(SOURCES);

export const built = () => SOURCE_IDS.filter((id) => SOURCES[id].state === 'built');
export const blocked = () => SOURCE_IDS.filter((id) => SOURCES[id].state !== 'built');

// What building one source would unlock, so the order of work is a
// calculation rather than an opinion.
export function impact(id, familiesBySource) {
  const src = SOURCES[id];
  if (!src) throw new Error('unknown source: ' + id);
  const fams = familiesBySource[id] || [];
  return {
    id,
    state: src.state,
    families: fams.length,
    candidates: fams.reduce((t, f) => t + (f.candidates || 0), 0),
    licence: src.licence,
    cost: src.cost,
    dependsOn: src.dependsOn || [],
    buildable: src.licence === 'open' || src.licence === 'open-sharealike' || src.licence === 'public-sector',
  };
}

export function validateRegistry() {
  const errors = [];
  for (const [id, src] of Object.entries(SOURCES)) {
    if (src.id !== id) errors.push(id + ' has a mismatched id');
    if (!STATES.includes(src.state)) errors.push(id + ' has state ' + src.state);
    if (!LICENCE_CLASSES[src.licence]) errors.push(id + ' has licence class ' + src.licence);
    if (!Array.isArray(src.unlocks) || !src.unlocks.length) errors.push(id + ' unlocks nothing, so nobody needs it');
    if (src.state === 'built' && !src.ingest) errors.push(id + ' is built with no ingest script recorded');
    if (src.state === 'built' && !src.store) errors.push(id + ' is built with no store recorded');
    if (src.commercialReuse === false && src.state === 'built') errors.push(id + ' is built and does not permit commercial reuse');
    for (const d of src.dependsOn || []) if (!SOURCES[d]) errors.push(id + ' depends on unknown source ' + d);
  }
  return errors;
}
