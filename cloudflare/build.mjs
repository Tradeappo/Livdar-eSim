// Bundle the Atlas Worker.
//
// The Worker renders the repository's own React components, so the bundle contains
// components/atlas/AtlasPage.jsx, Header.jsx, Footer.jsx and everything they import,
// plus react and react-dom's browser server renderer. Two adaptations are needed and
// they are the only two:
//
//   1. lib/atlas/serve-pages.js reads the cohort manifests with node:fs. It is the ONLY
//      filesystem dependency in the render chain, and the components use exactly one of
//      its functions (languagesServed). The resolver below swaps it for a shim. The swap
//      is done by RESOLVED PATH rather than by esbuild's `alias`, because every importer
//      reaches it by a different relative specifier ('../lib/atlas/serve-pages.js',
//      './serve-pages.js', ...) and an alias matches specifiers, not files.
//
//   2. process.env is read at module scope by lib/routes.js, lib/analytics.js and
//      lib/indexing.js. A Worker has no `process`, so one is injected.
//
// Everything else — the taxonomy, the vocabulary packs, the schema builder, the markets
// table — is pure JavaScript and bundles unchanged. Nothing in lib/ or components/ is
// edited for Cloudflare, which is the property that keeps one template serving both.

import { build, stop } from 'esbuild';
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const SHIM = join(HERE, 'src', 'shims', 'serve-pages.js');
const OUT = join(HERE, 'dist', 'worker.js');

// The stylesheets, in the order app/[lang]/layout.jsx and the route files import them,
// so the cascade is the production cascade.
const CSS_FILES = ['app/globals.css', 'app/shop.css', 'app/atlas.css'];

const css = (await Promise.all(CSS_FILES.map(async (rel) => {
  const body = await readFile(join(REPO, rel), 'utf8');
  return '/* ' + rel + ' */\n' + body;
}))).join('\n');
const etag = '"' + createHash('sha256').update(css).digest('hex').slice(0, 32) + '"';

await mkdir(join(HERE, 'src'), { recursive: true });
await writeFile(join(HERE, 'src', 'assets.generated.js'),
  '// GENERATED by cloudflare/build.mjs from ' + CSS_FILES.join(', ') + '. Do not edit.\n'
  + 'export const STYLESHEET_CSS = ' + JSON.stringify(css) + ';\n'
  + 'export const STYLESHEET_ETAG = ' + JSON.stringify(etag) + ';\n');

/** Redirect any import that resolves to lib/atlas/serve-pages.js to the Worker shim. */
const shimServePages = {
  name: 'shim-serve-pages',
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /serve-pages(\.js)?$/ }, (args) => {
      if (args.importer.startsWith(HERE) && args.path.includes('shims')) return null;
      const target = resolve(dirname(args.importer), args.path);
      if (target === join(REPO, 'lib', 'atlas', 'serve-pages.js')) return { path: SHIM };
      return null;
    });
  },
};

/** Fail the build if anything node-only survives into the bundle. */
const refuseNodeBuiltins = {
  name: 'refuse-node-builtins',
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^(node:|fs$|path$|crypto$|url$|os$|child_process$)/ }, (args) => ({
      errors: [{
        text: 'The Worker bundle reached the Node built-in "' + args.path + '" from ' + args.importer
          + '. A Worker has no filesystem; shim the module in cloudflare/src/shims/ rather than'
          + ' polyfilling it, and keep request-time code free of catalogue reads.',
      }],
    }));
  },
};

const result = await build({
  entryPoints: [join(HERE, 'src', 'worker.js')],
  outfile: OUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  // Dev-only React warning machinery is dead weight in the isolate and costs CPU on
  // every render; production React drops it.
  define: { 'process.env.NODE_ENV': '"production"' },
  inject: [join(HERE, 'src', 'shims', 'process.js')],
  plugins: [shimServePages, refuseNodeBuiltins],
  minify: true,
  legalComments: 'none',
  metafile: true,
  logLevel: 'info',
  conditions: ['worker', 'browser'],
  mainFields: ['browser', 'module', 'main'],
  loader: { '.css': 'empty' },
});

// The same render path, bundled for Node, so tests and the Vercel/Cloudflare SEO diff can
// render exactly what the Worker renders without starting esbuild themselves. esbuild's
// service is a child process that talks over stdio, and spawning it from inside
// `node --test` hangs the runner, so the harness is built HERE, once, as a build output.
await build({
  entryPoints: [join(HERE, 'src', 'render.jsx')],
  outfile: join(HERE, 'dist', 'render.harness.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  inject: [join(HERE, 'src', 'shims', 'process.js')],
  plugins: [shimServePages, refuseNodeBuiltins],
  conditions: ['worker', 'browser'],
  mainFields: ['browser', 'module', 'main'],
  loader: { '.css': 'empty' },
  logLevel: 'error',
});

const size = (await stat(OUT)).size;
const top = Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)
  .sort((a, b) => b[1].bytesInOutput - a[1].bytesInOutput).slice(0, 12)
  .map(([file, v]) => '  ' + (v.bytesInOutput / 1024).toFixed(1).padStart(7) + ' KB  ' + file);

console.log('\nworker bundle: ' + (size / 1024).toFixed(1) + ' KB  -> ' + OUT);
console.log('largest inputs:\n' + top.join('\n'));
// The Workers upload limit is 3 MB after gzip on the free plan and 10 MB on paid. Well
// under it is a property worth asserting rather than discovering at deploy time.
if (size > 8 * 1024 * 1024) throw new Error('worker bundle is ' + (size / 1048576).toFixed(1) + ' MB, over the 8 MB guard');
await writeFile(join(HERE, 'dist', 'meta.json'), JSON.stringify(result.metafile));
console.log('render harness: ' + join(HERE, 'dist', 'render.harness.mjs'));
stop();
